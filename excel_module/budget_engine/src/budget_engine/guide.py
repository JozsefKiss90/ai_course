"""The fill-in guide of a Handover Package: per sheet, what to enter, its unit and its source.

Generated from the build itself: one section per sheet the workbook has, in workbook order, so a
switched-off Estimation Method or a missing Task List has no section. Units, cost lines, unit-cost
sources and the transfer into the Submission Budget come from the Funding Profile. Every sheet the
engine can build has a section; a sheet without one fails the guide rather than going unexplained.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass
from typing import TYPE_CHECKING

from budget_engine.methods import equipment_depreciation, itemised_list, staff_effort, travel_planner
from budget_engine.profiles import Profile
from budget_engine.shape import ShapeParameters
from budget_engine.sheets import constants, cover, input_guards, rate_table, reference_lists, task_list, transfer_view

if TYPE_CHECKING:
    from budget_engine.build import BuildResult

NOTHING = "Nothing. Every cell is a formula or fixed data."


@dataclass(frozen=True)
class Section:
    enter: str
    unit: str
    source: str
    notes: tuple[str, ...] = ()


def fill_in_guide(result: BuildResult) -> str:
    profile, shape = result.profile, result.shape
    sections = _sections(profile, shape)
    lines = [
        f"# Fill-in guide: Planning Workbook for {profile.name}",
        "",
        f"Funding Profile {profile.id} {profile.version}. Workbook: `{result.path.name}`.",
        "",
        "## Before you start",
        "",
        "- Type only into light-yellow cells (Human Inputs). White cells are formulas: do not overwrite them.",
        "- The workbook is never submitted. You copy its Transfer Views into "
        f"{profile.submission_budget} by hand.",
        "- Lists that are Excel Tables grow: add a row inside the Table (Tab in its last cell, or Insert > Table Rows), "
        "never below it.",
        "- The Checks panel on the Cover shows OK / warning / error per guard while you fill in.",
        "- The workbook needs Excel 2021 or Microsoft 365 and contains no macros.",
        "",
        "## Fill-in order",
        "",
        *(f"{i}. {step}" for i, step in enumerate(result.fill_in_order, start=1)),
        "",
        "## Sheet by sheet",
    ]
    grouped: set[str] = set()
    for sheet in result.sheets:
        group = _group(profile, sheet)
        if group in grouped:
            continue
        grouped.add(group)
        if group not in sections:
            raise KeyError(f"the fill-in guide has no section for sheet {sheet!r}")
        section = sections[group]
        lines += [
            "",
            f"### {group}",
            "",
            f"- **What to enter:** {section.enter}",
            f"- **Unit:** {section.unit}",
            f"- **Source:** {section.source}",
            *(f"- {note}" for note in section.notes),
        ]
    lines += [
        "",
        f"## Transferring the Transfer Views into {profile.submission_budget}",
        "",
        *(f"{i}. {step}" for i, step in enumerate(profile.transfer_steps, start=1)),
    ]
    return "\n".join(lines) + "\n"


TRANSFER_VIEWS = "Transfer View sheets"
CHECK_SHEETS = "Check sheets"


def _group(profile: Profile, sheet: str) -> str:
    """The guide section a sheet belongs to: one for all Transfer Views, one for all Check sheets."""
    if sheet.startswith(transfer_view.SHEET_PREFIX):
        return TRANSFER_VIEWS
    if sheet in {part["sheet"] for part in profile.check_summaries.values() if isinstance(part, dict) and "sheet" in part}:
        return CHECK_SHEETS
    return sheet


def _sections(profile: Profile, shape: ShapeParameters) -> dict[str, Section]:
    be_sheet = str(profile.reference_lists["be_list"]["sheet"])
    wp_sheet = str(profile.reference_lists["wp_list"]["sheet"])
    staff = ", ".join(c.label for c in profile.staff_categories)
    grain = "task" if shape.tasks is not None else "work package"
    unit_costs = "; ".join(f"{t.title} ({t.source})" for t in profile.unit_cost_tables.values())
    thresholds = "; ".join(f"{t.label} ({t.unit})" for t in profile.plausibility)
    itemised_lines = "; ".join(itemised_list.cost_lines(profile).values()) if itemised_list.ID in shape.methods else ""
    builders: dict[str, Callable[[], Section]] = {
        cover.SHEET: lambda: Section(
            NOTHING, "-", "Generated by the build.",
            ("Shows the provenance (profile version, build date, Shape Parameters), the Checks panel, "
             "the fill-in order and the colour legend. Review the Checks panel last.",),
        ),
        be_sheet: lambda: Section(
            "For every Beneficiary and Affiliated Entity row: name, acronym, country (dropdown) and funding rate (dropdown).",
            "Text; the funding rate as a percentage.",
            "The consortium's own details, as they will appear in the Submission Budget.",
            (f"The layout is the same as the `{be_sheet}` of {profile.submission_budget}, so the same block can be pasted into both.",
             "A late Beneficiary or AE: add a row to the Table (an AE directly under its Beneficiary), then claim a "
             f"spare block by typing its BE/AE nr in the first free spare row of the `{rate_table.SHEET}`."),
        ),
        wp_sheet: lambda: Section(
            "The name of every work package.",
            "Text.",
            "The proposal's work plan.",
            (f"The layout is the same as the `{wp_sheet}` of {profile.submission_budget}.",),
        ),
        task_list.SHEET: lambda: Section(
            "The title of every task.",
            "Text.",
            "The proposal's work plan.",
            ("A task row added to the Table gets no staff effort rows until the workbook is rebuilt.",),
        ),
        input_guards.SHEET: lambda: Section(
            "The lead of each work package: a BE/AE nr from the dropdown.",
            "A BE/AE nr.",
            "The proposal's work plan.",
            ("The flags below the leads (effort without a rate) are formulas: read them, do not type.",),
        ),
        constants.SHEET: lambda: Section(
            f"Optional plausibility thresholds: {thresholds}. Leave a threshold blank to switch its warning off.",
            "As labelled beside each threshold.",
            "Your own judgement of what is implausible for this proposal; there are no defaults.",
            ("The Profile Constants above the thresholds are the Funding Profile's fixed conventions, each with its "
             "source. Formulas reference them; do not change them.",),
        ),
        reference_lists.COUNTRY_SHEET: lambda: Section(
            NOTHING, "-", f"The country list of {profile.submission_budget}, verbatim.",
            (f"Feeds the Country dropdown of the `{be_sheet}`.",),
        ),
        rate_table.SHEET: lambda: Section(
            f"A personnel rate for every Beneficiary/AE row and Staff Category ({staff}). In a spare row, first the "
            "BE/AE nr of the late partner that claims it.",
            profile.rate_unit,
            "Each Beneficiary's own personnel costs, by its usual cost accounting practices.",
        ),
        staff_effort.SHEET: lambda: Section(
            f"Effort per {grain}, Beneficiary/AE and Staff Category.",
            profile.effort_unit,
            "The proposal's work plan. The cost columns multiply the effort by the Rate Table: do not type them.",
        ),
        travel_planner.SHEET: lambda: Section(
            "One row per trip: " + ", ".join(name for _, name in travel_planner.INPUTS) + ".",
            "As in each column header; distances are one-way, in km.",
            f"The planned trips. Prices are looked up by formula from: {unit_costs}.",
            ("Distances under 400 km have no unit cost and show #N/A.",
             "The price columns are calculated: a trip row added to the Table is priced too."),
        ),
        travel_planner.SUMMARY_SHEET: lambda: Section(NOTHING, "-", f"Sums the `{travel_planner.SHEET}` per Beneficiary/AE and work package."),
        travel_planner.UNIT_COSTS_SHEET: lambda: Section(NOTHING, "EUR", unit_costs),
        equipment_depreciation.SHEET: lambda: Section(
            "One row per item: " + ", ".join(name for _, name in equipment_depreciation.INPUTS) + ".",
            "As in each column header; the usage share as a percentage.",
            "The planned purchases, with the depreciation period from the Beneficiary's own accounting.",
            ("Only the depreciation that falls within the project is costed, assuming purchase in project month 1.",),
        ),
        equipment_depreciation.SUMMARY_SHEET: lambda: Section(
            NOTHING, "-", f"Sums the `{equipment_depreciation.SHEET}` per Beneficiary/AE, work package and cost line."
        ),
        itemised_list.SHEET: lambda: Section(
            "One row per item: " + ", ".join(name for _, name in itemised_list.INPUTS) + ".",
            "As in each column header.",
            "Quotes, price lists or past costs for each item.",
            (f"The cost line is picked from the list beside the Table: {itemised_lines}.",),
        ),
        itemised_list.SUMMARY_SHEET: lambda: Section(
            NOTHING, "-", f"Sums the `{itemised_list.SHEET}` per Beneficiary/AE, work package and cost line."
        ),
        TRANSFER_VIEWS: lambda: Section(
            NOTHING,
            "As in the Submission Budget: number of items, average cost per item, total (EUR).",
            "Every Estimation Method contributing to a cost line, added up.",
            (f"One sheet per Beneficiary and AE, plus {shape.headroom} spare block(s) for late partners. "
             f"Copy them into {profile.submission_budget} as described at the end of this guide.",),
        ),
        CHECK_SHEETS: lambda: Section(
            NOTHING,
            "EUR, person-months and percentage shares.",
            f"The Transfer Views, summarised the way {profile.submission_budget} summarises them.",
            ("Compare them with the Submission Budget's own summaries after the transfer.",),
        ),
    }
    return {name: make() for name, make in builders.items()}
